def content_for(topic: str | None = None, question_id: str | None = None) -> str:
    if question_id:
        q = CU.QUESTIONS.get(question_id.strip())
        if not q:
            return f"No Learning Centre question has the id '{question_id}'."
        lines = [f"Question {question_id} ({q['type']}, {q['level']}): {q['q']}"]
        if q["type"] == "mcq":
            lines += [f"Option {chr(65 + i)}: {o}" + (" (correct)" if i == q["answer"] else f" - wrong because: {q['wrong'][i]}" if q["wrong"][i] else "")
                      for i, o in enumerate(q["options"])]
        else:
            lines.append(f"Correct answer: {q['answer']} {q.get('unit', '')} (accepted within ±{q['tolerance']:g})")
        lines.append(f"Explanation: {q['explain']}")
        if q.get("steps"):
            lines.append(f"Calculation: {q['steps']}")
        return "\n".join(lines)
    names = CU.find_terms(topic or "", 2)
    les = None
    if not names:
        les = next((x for x in CU.LESSONS.values() if (topic or "").lower() in x["title"].lower()), None) if topic else None
        if not les:
            return f"The Learning Centre has no lesson or glossary entry for '{topic}'. Say so, and explain only well-established general finance."
    out = []
    for n in names:
        e = CU.GLOSSARY_ENTRIES[n]
        out.append(f"Glossary: {n}\nDefinition: {e['definition']}" + (f"\nFormula: {e['formula']}" if e.get("formula") else "")
                   + (f"\nExample: {e['example']}" if e.get("example") else "") + (f"\nHow to read it: {e['interpretation']}" if e.get("interpretation") else ""))
        if les is None and CU.lessons_for_term(n):
            les = CU.LESSONS[CU.lessons_for_term(n)[0]]
    if les:
        out.append(f"Lesson: {les['title']} (module {CU.MODULE_BY_ID[les['module']]['title']}, {les['level']}; reviewed {CU.REVIEWED})\n"
                   f"Concept: {les['concept']}\nWhy it matters: {les['why']}\nFormulas / key rules: {'; '.join(les['formulas'] + les['rules'])}\n"
                   f"Worked example: {les['example']}\nInterpretation: {les['interpret']}\nCommon mistakes: {'; '.join(les['mistakes'])}\n"
                   f"Practice question ids: {', '.join(q['id'] for q in les['check'])}")
    return "\n\n".join(out)

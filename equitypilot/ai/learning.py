"""The assistant's learning mode, grounded in the Learning Centre curriculum. It works without any paid API.

Handles, when no company is named in the question:
  quiz      - "why is my answer wrong?" for a Learning Centre question id (e.g. ratios-returns:c1)
  practice  - practice questions on a topic, with answers and explanations at the end
  difference- the difference between two concepts (curated comparisons, else side-by-side glossary entries)
  example   - a fresh numerical example with made-up numbers, clearly labelled as illustrative
  steps     - a formula worked step by step
  simple    - a simpler explanation
  define    - definitions of terms that only the curriculum (not the classic glossary) covers
Formulas come from the curriculum and are computed with equitypilot.content.curriculum.calc; nothing is invented.
"""

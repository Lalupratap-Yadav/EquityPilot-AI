def _inr(x: float, d: int = 0) -> str:
    return f"₹{indian_group(x, d)}"


def _cr(x: float, d: int = 0) -> str:
    return f"₹{indian_group(x, d)} crore"


def _pct(x: float, d: int = 2) -> str:
    return f"{x * 100:.{d}f}%"


def _pick(rng: random.Random, lo: float, hi: float, step: float) -> float:
    n = int(round((hi - lo) / step))
    return round(lo + rng.randint(0, n) * step, 6)


